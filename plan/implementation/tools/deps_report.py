#!/usr/bin/env python3
"""Write the generated sections of plan/implementation/dependencies.md.

Reads the task graph through depcheck.py's `analyse()` and reports: a
summary of every check, the edge counts between areas and between
milestones, the accepted exceptions (gated edges, external gates, TBD
dependencies and split milestones) with the state of each gate in
plan/open-questions.md, and the tasks that most other tasks wait on.

Usage:

    python3 deps_report.py            # rewrite the generated sections
    python3 deps_report.py --check    # exit 1 if the file is out of date
    python3 deps_report.py --init     # rewrite the file from the skeleton
"""

import argparse
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
import depcheck  # noqa: E402
import epics  # noqa: E402
import gendoc as g  # noqa: E402

OUT = g.IMPL_DIR / "dependencies.md"
HUBS = 20
PLAN_NOTES = {
    "AC-LATER": "an acceptance criterion that applies from a later milestone "
                "than the task's own",
    "SPIKE-LEAF": "a spike task that no task depends on",
    "SPIKE-NOBOX": "a spike task that states no timebox",
    "RIG-PATH": "acceptance criteria name a rig, with no dependency path to "
                "the task that brings it online",
    "RIG-LATER": "acceptance criteria name a rig that comes online in a later "
                 "milestone",
}


def gate_state(oq, oq_rows, settled):
    """Where a gate's ID stands in plan/open-questions.md."""
    if oq in oq_rows:
        need = oq_rows[oq].get("needed by", "")
        res = g.abridge(oq_rows[oq].get("resolution", ""), 60)
        return f"open (needed by {need}; {res})"
    if oq in settled:
        row = settled[oq]
        still = row.get("still open", "—").strip()
        txt = f"**settled** by {row.get('settled by', '?')}"
        if still and still not in ("—", "-"):
            txt += f"; still open: {still}"
        return txt
    return "**not in the register**"


def build():
    res = depcheck.analyse()
    tasks = res["tasks"]
    count = defaultdict(int)
    for p in res["problems"]:
        count[p["kind"]] += 1
    ncount = defaultdict(int)
    for n in res["notes"]:
        ncount[n["kind"]] += 1
    edges = res["edges"]
    gated = [e for e in edges if e["gate"]]
    m0_bad = len({p["task"] for p in res["problems"]
                  if p["kind"] == "M0CLOSURE"})

    # Summary
    rows = [
        ["WORDFORM", "a Depends cell segment outside the grammar",
         count["WORDFORM"]],
        ["DANGLING", "a dependency on a task ID that does not exist",
         count["DANGLING"]],
        ["CYCLE", "tasks that depend on each other, directly or not",
         f"{count['CYCLE']} ({sum(len(c) for c in res['cycles'])} tasks)"],
        ["LATER", "a task depending on a task in a later milestone",
         count["LATER"]],
        ["M0CLOSURE", "an M0 task reaching a non-M0 task, or an M0a task "
         "reaching a task outside M0a",
         f"{count['M0CLOSURE']} ({m0_bad} M0 tasks)"],
        ["MULTI", "a Milestone cell naming more than one milestone",
         count["MULTI"]],
        ["MALFORMED", "a task row the parser could not read",
         count["MALFORMED"]],
        ["DUPLICATE", "a task ID used twice", count["DUPLICATE"]],
    ]
    fatal = sum(count[k] for k in depcheck.FATAL)
    lines = [
        f"Generated by `tools/deps_report.py` from {len(tasks)} tasks and "
        f"{len(edges)} dependency edges (an edge reads \"task depends on "
        f"prerequisite\").",
        "",
        g.table(["Check", "Meaning", "Count"], rows),
        "",
        g.table(["Not a problem, listed below", "Count"], [
            ["edges accepted as milestone exceptions by a `gate:` note",
             len(gated)],
            ["SPLIT edges (multi-milestone cells)", ncount["SPLIT"]],
            ["`TBD:` dependencies (no task delivers them yet)",
             f"{len(res['tbds'])} ({ncount['M0-TBD']} in M0)"],
            ["`gate:` segments (external gates, no edge)",
             len(res["gates"])],
            ["task IDs inside notes (not edges)", ncount["NOTE-ID"]],
            ["plan-rule notes (AC-LATER, SPIKE-LEAF, SPIKE-NOBOX, RIG-PATH, "
             "RIG-LATER), listed under Exceptions",
             sum(ncount[k] for k in PLAN_NOTES)],
        ]),
        "",
    ]
    if fatal == 0 and not gated:
        lines.append(
            "**Status.** Cycles, later-milestone dependencies and M0-closure "
            "problems are all zero, and no edge needs a milestone exception. "
            "Every task sits in exactly one milestone, and every dependency "
            "is either a task ID or an external gate.")
    else:
        lines.append(
            f"**Status.** {fatal} problems. Run `python3 depcheck.py` for "
            "the list.")
        for kind in ("CYCLE", "LATER", "M0CLOSURE"):
            ps = [p for p in res["problems"] if p["kind"] == kind]
            if ps:
                lines.append("")
                lines.append(g.table(
                    ["Kind", "Task", "Detail"],
                    [[kind, p["task"], g.cell(p["detail"])] for p in ps]))
        if gated:
            lines.append("")
            lines.append("Milestone exceptions accepted by a gate:")
            lines.append("")
            lines.append(g.table(
                ["Task", "Depends on", "Gate"],
                [[e["from"], e["to"], e["gate"]] for e in gated]))
    summary = "\n".join(lines)

    # Cross-area matrix
    mat = defaultdict(int)
    for e in edges:
        mat[(tasks[e["from"]]["area"], tasks[e["to"]]["area"])] += 1
    rows = []
    for a in g.AREAS:
        row = [a] + [mat[(a, b)] for b in g.AREAS]
        out_cross = sum(mat[(a, b)] for b in g.AREAS if b != a)
        rows.append(row + [sum(mat[(a, b)] for b in g.AREAS), out_cross])
    rows.append(["Total"] + [sum(mat[(a, b)] for a in g.AREAS)
                             for b in g.AREAS]
                + [len(edges), sum(v for (a, b), v in mat.items()
                                   if a != b)])
    cross = sum(v for (a, b), v in mat.items() if a != b)
    pairs = sorted(((v, a, b) for (a, b), v in mat.items() if a != b),
                   key=lambda x: (-x[0], g.AREAS.index(x[1]),
                                  g.AREAS.index(x[2])))
    areas_md = "\n".join([
        f"Rows are the dependent task's area, columns the prerequisite's. "
        f"{cross} of the {len(edges)} edges ({100 * cross // len(edges)}%) "
        "cross an area boundary.",
        "",
        g.table(["Depends on →", *g.AREAS, "All", "Cross-area"], rows),
        "",
        "Area pairs by number of cross-area edges:",
        "",
        g.table(["Dependent area", "Prerequisite area", "Edges"],
                [[a, b, v] for v, a, b in pairs]),
    ])

    # Milestone matrix
    mm = defaultdict(int)
    for e in edges:
        mm[(tasks[e["from"]]["first"], tasks[e["to"]]["first"])] += 1
    rows = [[g.label(a)] + [mm[(a, b)] for b in g.MILESTONES]
            for a in g.MILESTONES]
    milestones_md = "\n".join([
        "Rows are the dependent task's milestone, columns the "
        "prerequisite's, in delivery order; a plain M0 cell counts as M0b "
        "and a plain M1 cell as M1a. Every count above the diagonal would be "
        "a LATER edge.",
        "",
        g.table(["Depends on →", *[g.label(m) for m in g.MILESTONES]],
                rows),
    ])

    # Exceptions and external gates
    oqs, settled_rows = g.open_questions()
    oq_rows = {q["id"]: q for q in oqs}
    settled = {s["id"]: s for s in settled_rows if s.get("id")}
    gate_rows = []
    closed = missing = 0
    for gt in sorted(res["gates"], key=lambda x: epics.id_key(x["task"])):
        state = gate_state(gt["gate"], oq_rows, settled)
        if "**settled**" in state:
            closed += 1
        elif "not in the register" in state:
            missing += 1
        gate_rows.append([gt["task"], tasks[gt["task"]]["milestone"],
                          g.cell(gt["text"]), state])
    ex = []
    if gate_rows:
        ex.append("External gates: `gate:` segments in a Depends cell. "
                  "They add no edge; the task cannot finish until the gate "
                  "closes. \"State\" is the gate's row in "
                  "`plan/open-questions.md`. A settled gate no longer holds "
                  "its task.")
        ex.append("")
        ex.append(g.table(["Task", "Milestone", "Gate as written", "State"],
                          gate_rows))
        if closed:
            ex.append("")
            ex.append(f"{closed} gate(s) cite a settled question. They no "
                      "longer gate their task, and the area can drop the "
                      "segment.")
        if missing:
            ex.append("")
            ex.append(f"{missing} gate(s) cite an ID missing from the "
                      "register. The area should re-point each one to the "
                      "open question that still carries it, or to the ADR "
                      "or RFC section that settled it.")
    else:
        ex.append("No external gates.")
    if res["tbds"]:
        ex.append("")
        ex.append("`TBD:` dependencies:")
        ex.append("")
        ex.append(g.table(["Task", "Milestone", "What is needed"],
                          [[t["task"], t["milestone"], g.cell(t["text"])]
                           for t in res["tbds"]]))
    else:
        ex.append("")
        ex.append("No `TBD:` dependencies.")
    splits = [n for n in res["notes"] if n["kind"] == "SPLIT"]
    if splits:
        ex.append("")
        ex.append(g.table(["SPLIT edge"],
                          [[g.cell(n["detail"])] for n in splits]))
    ex.append("")
    ex.append("Plan-rule notes. None of them fails the check; each one is a "
              "row for its area to fix under the milestone rules in RFC-0001 "
              "§16.")
    ex.append("")
    ex.append(g.table(["Note", "Meaning", "Tasks"], [
        [k, why, g.counted(n["task"] for n in res["notes"] if n["kind"] == k)]
        for k, why in PLAN_NOTES.items()]))
    exceptions_md = "\n".join(ex)

    # Hubs
    dependents = defaultdict(list)
    deps = defaultdict(list)
    for e in edges:
        dependents[e["to"]].append(e["from"])
        deps[e["from"]].append(e["to"])
    hubs = sorted(tasks, key=lambda t: (-len(dependents[t]),
                                        epics.id_key(t)))[:HUBS]
    hub_rows = []
    for t in hubs:
        r = tasks[t]
        areas = defaultdict(int)
        for d in dependents[t]:
            areas[tasks[d]["area"]] += 1
        hub_rows.append([t, r["milestone"],
                         g.cell(g.abridge(re.sub(r"\*\*", "", r["task"]),
                                          90)),
                         len(dependents[t]),
                         ", ".join(f"{a} {areas[a]}" for a in g.AREAS
                                   if areas[a])])
    roots = [t for t in tasks if not deps[t]]
    leaves = [t for t in tasks if not dependents[t]]
    hubs_md = "\n".join([
        f"The {HUBS} tasks with the most direct dependents. A change to one "
        "of their interfaces reaches every area in the last column. "
        f"{len(roots)} tasks depend on nothing; {len(leaves)} tasks have no "
        "dependents.",
        "",
        g.table(["Task", "Milestone", "What", "Direct dependents",
                 "Dependents by area"], hub_rows),
    ])
    return {"deps-summary": summary, "deps-areas": areas_md,
            "deps-milestones": milestones_md,
            "deps-exceptions": exceptions_md, "deps-hubs": hubs_md}


SKELETON = f"""# Dependencies: checks and cross-area edges

This file summarises the dependency graph of the six epic files. Every "Depends on" cell in `epics/` is written in the grammar that `tools/README.md` defines: task IDs, ranges inside one epic, `none`, `TBD:` for work no task delivers yet, and `gate:` for an external gate, an open question in `plan/open-questions.md`. `tools/depcheck.py` checks the graph, and `tools/deps_report.py` writes the generated sections below from its result. Re-run both after any change to an epic file:

```sh
python3 plan/implementation/tools/depcheck.py           # every problem, then the summary
python3 plan/implementation/tools/deps_report.py        # rewrite the generated sections
python3 plan/implementation/tools/deps_report.py --check   # exit 1 if this file is stale
```

A dependency fix is recorded in `dependency-fixes.md`, under the rule it follows. To see one task's edges in both directions, run `python3 plan/implementation/tools/depcheck.py --task <ID>`.

## Summary

{g.marker("deps-summary")}

## Edges between areas

{g.marker("deps-areas")}

## Edges between milestones

{g.marker("deps-milestones")}

## Exceptions and external gates

{g.marker("deps-exceptions")}

## Most depended-on tasks

{g.marker("deps-hubs")}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if dependencies.md is out of date")
    ap.add_argument("--init", action="store_true",
                    help="rewrite the whole file from the skeleton")
    args = ap.parse_args()
    return g.write_sections(OUT, SKELETON, build(), init=args.init,
                            check=args.check)


if __name__ == "__main__":
    sys.exit(main())
