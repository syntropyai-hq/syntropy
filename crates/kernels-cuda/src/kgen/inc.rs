//! The explicit instantiation lists, `csrc/instantiate/<unit>.inc` (RFC-0040 §10.2 rule 2).
//!
//! One line per (op key, tile), in `OpKey` order then tile order, so the same table always
//! gives the same bytes. Each line is a call of the unit's `SYN_INSTANTIATE` macro, which the
//! unit defines before it includes the list:
//!
//! ```text
//! SYN_INSTANTIATE(<op>, <weight>, <activation>, <output>, <layout>, <fusion bits>, <tile>)
//! ```
//!
//! Each name is a C identifier made from the value's Rust form: `GEMV`, `GGML_Q4_K`,
//! `PLAIN_F32`. A key with fewer than three schemes pads with `NONE`. The list is part of the
//! unit's `ObjectKey` (ADR-0623 decision 1), so adding an instantiation misses the cache.

use std::fmt::{Debug, Write as _};

use super::support::SupportEntry;
use super::units::Unit;

/// A C identifier for a value's `Debug` form: every run of characters that are not ASCII
/// letters or digits becomes one `_`, trimmed at both ends, in upper case.
/// `GateUpAct { act: Silu }` becomes `GATEUPACT_ACT_SILU`, `Ggml(Q4_K)` becomes `GGML_Q4_K`.
#[must_use]
pub fn c_ident(value: &impl Debug) -> String {
    let text = format!("{value:?}");
    let mut out = String::with_capacity(text.len());
    let mut gap = false;
    for c in text.chars() {
        if c.is_ascii_alphanumeric() {
            if gap && !out.is_empty() {
                out.push('_');
            }
            gap = false;
            out.push(c.to_ascii_uppercase());
        } else {
            gap = true;
        }
    }
    out
}

/// The instantiation list of `unit` from its entries in `support.toml`.
#[must_use]
pub fn render(unit: &Unit, entries: &[SupportEntry]) -> String {
    let mut out = String::new();
    out.push_str("// SPDX-License-Identifier: MIT OR Apache-2.0\n");
    let _ = writeln!(
        out,
        "// @generated by `cargo xtask kgen` from crates/kernels-cuda/support.toml. Do not edit."
    );
    let _ = writeln!(
        out,
        "// Unit {}: {:?} ops, {:?} weight schemes; contraction {} (RFC-0040 §10.2).",
        unit.name,
        unit.family,
        unit.group,
        if unit.bit_exact {
            "off, bit-exact class"
        } else {
            "allowed"
        }
    );
    for entry in entries {
        let key = &entry.key;
        let op = c_ident(&key.op);
        let scheme = |i: usize| key.schemes.get(i).map_or("NONE".to_owned(), c_ident);
        let tiles: &[u32] = if entry.tiles.is_empty() {
            &[0]
        } else {
            &entry.tiles
        };
        for tile in tiles {
            let _ = writeln!(
                out,
                "SYN_INSTANTIATE({op}, {}, {}, {}, {}, 0x{:04x}, {tile})",
                scheme(0),
                scheme(1),
                scheme(2),
                key.layout.0,
                key.variant
            );
        }
    }
    out
}
