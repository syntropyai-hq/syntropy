//! The golden vectors, built from RFC-0030 §6.2's formulas without `syntropy_cluster::pairing`:
//! each hashed input is concatenated here field by field, and hashed with the reference `blake3`
//! crate. The tests then check the library against these bytes.

use std::fmt::Write;

use super::model::SplitMix64;

/// One pairing: the inputs both sides hold once the exchange is done.
pub struct Vector {
    pub name: &'static str,
    pub about: &'static str,
    pub cluster_id: [u8; 32],
    pub joiner: [u8; 32],
    pub keyholder: [u8; 32],
    pub nonce_c: [u8; 16],
    pub nonce_k: [u8; 16],
}

/// `"syntropy-sas-commit-v1" ‖ joiner ‖ nonce_c`.
pub fn commit_input(v: &Vector) -> Vec<u8> {
    let mut out = b"syntropy-sas-commit-v1".to_vec();
    out.extend_from_slice(&v.joiner);
    out.extend_from_slice(&v.nonce_c);
    out
}

/// `"syntropy-sas-v1" ‖ cluster_id ‖ joiner ‖ keyholder ‖ nonce_c ‖ nonce_k`.
pub fn sas_input(v: &Vector) -> Vec<u8> {
    let mut out = b"syntropy-sas-v1".to_vec();
    out.extend_from_slice(&v.cluster_id);
    out.extend_from_slice(&v.joiner);
    out.extend_from_slice(&v.keyholder);
    out.extend_from_slice(&v.nonce_c);
    out.extend_from_slice(&v.nonce_k);
    out
}

/// `u32_le(digest[0..4])`.
pub fn sas_word(digest: &[u8; 32]) -> u32 {
    u32::from_le_bytes([digest[0], digest[1], digest[2], digest[3]])
}

/// The code: the word mod 10⁶.
pub fn sas(v: &Vector) -> u32 {
    sas_word(blake3::hash(&sas_input(v)).as_bytes()) % 1_000_000
}

fn counting<const N: usize>(start: u8) -> [u8; N] {
    std::array::from_fn(|i| start.wrapping_add(i as u8))
}

/// The committed vectors.
pub fn vectors() -> Vec<Vector> {
    let counting_vector = || Vector {
        name: "counting",
        about: "each field counts up from where the previous one stopped",
        cluster_id: counting(0x00),
        joiner: counting(0x20),
        keyholder: counting(0x40),
        nonce_c: counting(0x60),
        nonce_k: counting(0x70),
    };
    let base = counting_vector();
    let mut rng = SplitMix64(0x5359_4E54_5041_4952);
    let seeded = Vector {
        name: "seeded",
        about: "fields drawn from SplitMix64 with seed 0x53594e5450414952",
        cluster_id: rng.key(),
        joiner: rng.key(),
        keyholder: rng.key(),
        nonce_c: rng.nonce(),
        nonce_k: rng.nonce(),
    };
    // The first value of nonce_k's last two bytes, counting up from zero, whose code is below
    // 1,000, so the vector shows the leading zeros.
    let mut leading_zeros = Vector {
        name: "leading-zeros",
        about: "the counting vector with nonce_k[14..16] set to the first value whose code is below 1000",
        ..counting_vector()
    };
    for n in 0..=u16::MAX {
        leading_zeros.nonce_k[14..].copy_from_slice(&n.to_be_bytes());
        if sas(&leading_zeros) < 1000 {
            break;
        }
    }
    assert!(
        sas(&leading_zeros) < 1000,
        "no code below 1000 in 65,536 tries"
    );
    let roles_swapped = Vector {
        name: "roles-swapped",
        about: "the counting vector with joiner and keyholder swapped; its code differs",
        joiner: base.keyholder,
        keyholder: base.joiner,
        ..counting_vector()
    };
    vec![
        Vector {
            name: "zeros",
            about: "every field zero",
            cluster_id: [0; 32],
            joiner: [0; 32],
            keyholder: [0; 32],
            nonce_c: [0; 16],
            nonce_k: [0; 16],
        },
        base,
        roles_swapped,
        seeded,
        leading_zeros,
    ]
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// The vectors file: for each pairing, its inputs, the three messages' pairing fields in the
/// order they travel, the bytes each derivation hashes, and the results.
pub fn render(vectors: &[Vector]) -> String {
    let mut out = String::from(
        "# LAN pairing vectors (RFC-0030 §6.2, §6.7), frozen by DIST-E5-T14 for DIST-E5-T03.\n\
         # Generated by crates/cluster/tests/pairing/spec.rs. A change to this file changes the\n\
         # pairing protocol.\n\
         #\n\
         # commit = BLAKE3(\"syntropy-sas-commit-v1\" ‖ joiner ‖ nonce_c)\n\
         # sas    = u32_le(BLAKE3(\"syntropy-sas-v1\" ‖ cluster_id ‖ joiner ‖ keyholder ‖ nonce_c ‖ nonce_k)[0..4]) mod 10^6\n\
         #\n\
         # The pairing fields travel in this order: PairRequest.commit (32 bytes),\n\
         # PairChallenge.nonce_k (16 bytes), then PairReveal.nonce_c (16 bytes), which the joiner\n\
         # sends only after PairChallenge has arrived. Hex is lowercase, byte order as hashed.\n",
    );
    for v in vectors {
        let commit_in = commit_input(v);
        let sas_in = sas_input(v);
        let digest = blake3::hash(&sas_in);
        let word = sas_word(digest.as_bytes());
        let code = word % 1_000_000;
        let _ = write!(
            out,
            "\n[{name}] {about}\n\
             cluster_id            = {cluster_id}\n\
             joiner                = {joiner}\n\
             keyholder             = {keyholder}\n\
             nonce_c               = {nonce_c}\n\
             nonce_k               = {nonce_k}\n\
             commit_input          = {commit_in}\n\
             PairRequest.commit    = {commit}\n\
             PairChallenge.nonce_k = {nonce_k}\n\
             PairReveal.nonce_c    = {nonce_c}\n\
             sas_input             = {sas_in}\n\
             sas_digest            = {digest}\n\
             sas_word              = {word:#010x} ({word})\n\
             sas                   = {code}\n\
             shown                 = {shown}\n",
            name = v.name,
            about = v.about,
            cluster_id = hex(&v.cluster_id),
            joiner = hex(&v.joiner),
            keyholder = hex(&v.keyholder),
            nonce_c = hex(&v.nonce_c),
            nonce_k = hex(&v.nonce_k),
            commit_in = hex(&commit_in),
            commit = hex(blake3::hash(&commit_in).as_bytes()),
            sas_in = hex(&sas_in),
            digest = hex(digest.as_bytes()),
            shown = format_args!("{:03} {:03}", code / 1000, code % 1000),
        );
    }
    out
}
